export function busLanguage(language) {
  return String(language || "en").toLowerCase().split(/[-_]/)[0];
}

export function busText(language, key, values = {}) {
  const text = busTranslations[busLanguage(language)]?.[key] ?? busTranslations.en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (match, name) => String(values[name] ?? match));
}
